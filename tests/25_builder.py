    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 390, 'height': 844}, timezone_id='Europe/London')
    ctx.grant_permissions(['clipboard-read', 'clipboard-write'], origin='https://sorted.test')
    ctx.route('https://cdn.jsdelivr.net/**', lambda r: r.fulfill(path=HERE + '/tests/mock.js', content_type='application/javascript'))
    ctx.route(lambda u: u.startswith('https://sorted.test/'), lambda r: r.fulfill(path=HERE + '/tests/out/index.html', content_type='text/html') if '/art/' not in r.request.url else r.fulfill(body=''))
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('https://sorted.test/#start'); pg.evaluate("localStorage.clear();localStorage.setItem('__emailReady','1')"); pg.reload(); wait(pg, 200); pg.click('[data-a=anon-start]'); wait(pg)
    T = 'Southwark PCN · SK12345678'
    start(pg, "London Borough of Southwark PENALTY CHARGE NOTICE PCN Number: SK12345678 Vehicle Registration Mark: AB12 CDE Date of contravention: %s Location: Lordship Lane SE22 Contravention code: 12 Parked in a residents' or shared use parking place without a permit. The penalty charge is £130. If paid within 14 days, reduced to £65." % uk(-2))
    ok(pg.locator('.pk-card [data-a=panel][data-p=pkbuild]').inner_text() == 'Help me write a challenge', 'the parking card offers to help write the challenge')
    pg.click('.pk-card [data-a=panel][data-p=pkbuild]'); wait(pg)
    ok('Sorted only writes what you tick' in pg.inner_text('main'), 'it says it only writes what you tick')
    ok(pg.locator('input[name=bdg-sold]').count() == 0, 'no "didn’t own it" option at the ticket stage')
    pg.click('form[data-f=pkbuild] button[type=submit]'); wait(pg)
    ok('Tick at least one thing' in pg.inner_text('main'), 'nothing ticked: it asks for at least one reason')
    ok(pg.locator('textarea[name=bdd-paid]').is_visible() is False, 'the "own words" box only opens when you tick')
    pg.check('input[name=bdg-paid]'); wait(pg, 100)
    ok(pg.locator('textarea[name=bdd-paid]').is_visible(), 'ticking opens the "own words" box')
    pg.fill('textarea[name=bdd-paid]', 'I paid at 10:05 on RingGo, session 445821')
    pg.check('input[name=bde-receipt]')
    pg.click('form[data-f=pkbuild] button[type=submit]'); wait(pg)
    draft = pg.input_value('#f-bdtext')
    ok(draft.startswith('Dear Southwark Council,') and ('Penalty Charge Notice SK12345678, vehicle AB12 CDE, %s, Lordship Lane SE22.' % lab(-2)) in draft, 'it opens with who and the confirmed details')
    ok('I am challenging this penalty charge and ask you to cancel it.' in draft, 'it says what you want')
    ok('I paid for parking for this time. I paid at 10:05 on RingGo, session 445821.' in draft, 'it uses your reason in your words')
    ok('I have attached a payment receipt or app screenshot.' in draft and 'please offer the reduced amount again' in draft, 'it lists your evidence and asks for the reduced amount again')
