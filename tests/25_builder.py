    t = case(pg, T)
    ok(t['pk']['subs'][0]['text'].startswith('Dear Southwark Council,') and 'Baldwin Example' in t['pk']['subs'][0]['text'], 'the exact words you sent are kept in the case')
    # formal stage
    start(pg, "London Borough of Camden NOTICE TO OWNER PCN Number: CU98765432 Vehicle: LK70 XYZ Date of notice: %s Date of contravention: %s The penalty charge of £160 has not been paid." % (uk(-1), uk(-20)))
    ok(pg.locator('.pk-card [data-a=panel][data-p=pkbuild]').inner_text() == 'Help me write a formal challenge', 'Notice to Owner: help with a formal challenge')
    pg.click('.pk-card [data-a=panel][data-p=pkbuild]'); wait(pg)
    ok(pg.locator('input[name=bdg-sold]').count() == 1, '"I didn’t own the vehicle then" is offered at this stage')
    pg.check('input[name=bdg-sold]'); pg.fill('textarea[name=bdd-sold]', 'I sold it on 1 August'); pg.click('form[data-f=pkbuild] button[type=submit]'); wait(pg)
    draft = pg.input_value('#f-bdtext')
    ok('I am making formal representations against this Notice to Owner and ask you to cancel it.' in draft and 'I did not own the vehicle at the time. I sold it on 1 August.' in draft, 'formal wording, your reason')
    ok('reduced amount' not in draft, 'no reduced-price line when there isn’t one')
